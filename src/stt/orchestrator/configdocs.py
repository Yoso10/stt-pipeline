"""The `config-docs` command: generate the key reference `docs/CONFIG_REFERENCE.md` from the config schemas (never written by hand).

How to run (project root):
    python -m stt config-docs                      # writes docs/CONFIG_REFERENCE.md
    python -m stt config-docs --out my_reference.md
Example output (stderr):
    Wrote docs/CONFIG_REFERENCE.md: 20 sections, 190 keys.
What it does: reads the pydantic schema classes of every registered config section (the composition root passes them in), and writes one table per section with the full dotted key (what `--set` uses), the type,
the default, the status tag and the explanation. It only READS the schemas: it cannot change a key or a default. The output is deterministic (no date, no machine data), so a test can compare it with the file
in the repository: the test fails when the file is out of date (run the command again).
The status tag is the tag at the start of the key's own description in the code (`DEFAULT`, `NEW`, `REQUIRED`, ...). A key whose description has no tag gets `DEFAULT` when it has a default value and `REQUIRED`
when it has none. The schemas carry NO `LOCKED` mark: which choices are locked is recorded in docs/DECISIONS.md and docs/PRD.md, not in the code.
Errors: OrchestratorError (exit code 2) when the output file exists and was not made by this command (it is not overwritten), or its folder does not exist.
"""

from __future__ import annotations

import json
import re
import types
import typing
from collections.abc import Mapping
from enum import Enum
from pathlib import Path, PurePath
from typing import Any

from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from stt.orchestrator.errors import OrchestratorError

MARKER = "<!-- Generated by `python -m stt config-docs`. Do not edit by hand. -->"
TAG = re.compile(r"^(DEFAULT|NEW|REQUIRED|LOCKED|OPEN|PENDING)\b")
MAX_DEFAULT_CHARS = 160


def type_name(annotation: Any) -> str:
    """A short readable name of a type annotation (`int`, `list[str]`, `Path | None`, `'a' | 'b'`)."""
    if annotation is None or annotation is type(None):
        return "None"
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Annotated:
        return type_name(args[0])
    if origin is typing.Literal:
        return " | ".join(repr(a) for a in args)
    if origin is typing.Union or origin is types.UnionType:
        return " | ".join(type_name(a) for a in args)
    if origin is not None:
        base = getattr(origin, "__name__", str(origin))
        return f"{base}[{', '.join(type_name(a) for a in args)}]" if args else base
    if isinstance(annotation, type):
        return annotation.__name__
    return str(annotation).replace("typing.", "")


def _model_of(annotation: Any) -> type[BaseModel] | None:
    """The nested model class of a field type (`X` or `X | None`), or None for a plain value."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    if typing.get_origin(annotation) in (typing.Union, types.UnionType):
        models = [a for a in typing.get_args(annotation) if isinstance(a, type) and issubclass(a, BaseModel)]
        if len(models) == 1:
            return models[0]
    return None


def _plain(value: Any) -> Any:
    """A default as plain data for JSON (paths as posix text, enums as their value, models as dicts)."""
    if isinstance(value, BaseModel):
        return _plain(value.model_dump(mode="python"))
    if isinstance(value, PurePath):
        return value.as_posix()
    if isinstance(value, Enum):
        return _plain(value.value)
    if isinstance(value, Mapping):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [_plain(v) for v in value]
    return value


def default_text(field: FieldInfo) -> str:
    """The default of a field as text (`(required)` when it has none). A long default is shortened with an ellipsis."""
    if field.is_required():
        return "(required)"
    value = field.get_default(call_default_factory=True)
    if value is PydanticUndefined:
        return "(required)"
    text = json.dumps(_plain(value), ensure_ascii=False, default=str, sort_keys=False)
    return text if len(text) <= MAX_DEFAULT_CHARS else text[: MAX_DEFAULT_CHARS - 1] + "…"


def status_tag(field: FieldInfo) -> str:
    """The tag at the start of the description, else DEFAULT (has a default value) or REQUIRED (has none)."""
    match = TAG.match(field.description or "")
    if match:
        return match.group(1)
    return "REQUIRED" if field.is_required() else "DEFAULT"


def _cell(text: str) -> str:
    """Text for one table cell: one line, no pipe characters that would break the table."""
    return " ".join(text.split()).replace("|", "\\|")


def _rows(model: type[BaseModel], prefix: str) -> list[tuple[str, str, str, str, str]]:
    """(key, type, default, status, description) for every leaf key of `model`, nested models flattened with dotted keys."""
    rows: list[tuple[str, str, str, str, str]] = []
    for name, field in model.model_fields.items():
        key = f"{prefix}.{name}"
        nested = _model_of(field.annotation)
        if nested is not None:
            rows.extend(_rows(nested, key))
        else:
            rows.append((key, type_name(field.annotation), default_text(field), status_tag(field), field.description or ""))
    return rows


def render_config_reference(sections: Mapping[str, type[BaseModel]]) -> str:
    """The text of `docs/CONFIG_REFERENCE.md` for `sections` (name -> schema class), in the order given. Deterministic."""
    lines = [
        MARKER,
        "# Config key reference",
        "",
        "HOW TO RUN: `python -m stt config-docs` writes this file again from the code (add `--out FILE` for another place). Never edit it by hand: a test fails when it is out of date.",
        "Use a key in a config file as `section:` / `key:` (nested keys are nested blocks), or on the command line as `--set section.key=value` (lists and dicts as JSON).",
        "",
        "Status column: the tag at the start of the key's description in the code (`DEFAULT` = a starting value you may change, `NEW` = added after the original brief, `REQUIRED` = no default, you must set it). "
        "A key without a tag shows `DEFAULT` or `REQUIRED` from its default value. The code carries no `LOCKED` mark: the locked choices are in docs/DECISIONS.md and docs/PRD.md.",
        "",
        "## Sections",
        "",
    ]
    tables = []
    total = 0
    for name, model in sections.items():
        rows = _rows(model, name)
        total += len(rows)
        tables.append((name, model, rows))
        lines.append(f"- [`{name}`](#section-{name}): {len(rows)} keys")
    lines.append("")
    for name, model, rows in tables:
        doc = " ".join((model.__doc__ or "").split())
        lines.append(f'<a id="section-{name}"></a>')
        lines.append(f"## `{name}`")
        lines.append("")
        if doc:
            lines.append(doc)
            lines.append("")
        lines.append("| Key | Type | Default | Status | Description |")
        lines.append("|---|---|---|---|---|")
        for key, type_, default, status, description in rows:
            lines.append(f"| `{key}` | {_cell(type_)} | {_cell(default)} | {status} | {_cell(description)} |")
        lines.append("")
    lines.append(f"Total: {len(tables)} sections, {total} keys.")
    return "\n".join(lines) + "\n"


def count_keys(text: str) -> tuple[int, int]:
    """(sections, keys) of a rendered reference, read from its last line."""
    match = re.search(r"Total: (\d+) sections, (\d+) keys\.\s*$", text)
    return (int(match.group(1)), int(match.group(2))) if match else (0, 0)


def write_reference(text: str, target: Path) -> Path:
    """Write the reference to `target`. An existing file is replaced ONLY when it was made by this command (it starts with the generated marker).

    Errors: OrchestratorError (exit code 2) for another existing file, or a folder that does not exist.
    """
    if not target.parent.is_dir():
        raise OrchestratorError(f"The folder of {target} does not exist. Create it, or choose another --out.", exit_code=2)
    if target.exists():
        first = target.read_text(encoding="utf-8", errors="replace").splitlines()[:1]
        if first != [MARKER]:
            raise OrchestratorError(f"{target} exists and was not made by `config-docs` (it does not start with the generated marker). It is not overwritten: choose another --out, or move that file away yourself.", exit_code=2)
    target.write_text(text, encoding="utf-8", newline="\n")
    return target
